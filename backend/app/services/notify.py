# backend/app/services/notify.py
"""Send key-factor emails via Resend. Uses urllib (stdlib) so no extra dep."""
import json
import urllib.request

from app.config import EMAIL_DISABLED, EMAIL_FROM, RESEND_API_KEY

RESEND_URL = "https://api.resend.com/emails"


def send_toss_email(to: str, subject: str, html: str) -> tuple[bool, str]:
    """Send one HTML email. Returns (ok, detail). SILENTLY no-ops when the
    feature is disabled or no API key is configured."""
    if EMAIL_DISABLED or not RESEND_API_KEY:
        return False, "email disabled / no RESEND_API_KEY"

    payload = json.dumps({"from": EMAIL_FROM, "to": [to], "subject": subject, "html": html}).encode("utf-8")
    req = urllib.request.Request(
        RESEND_URL,
        data=payload,
        method="POST",
        headers={
            "Authorization": f"Bearer {RESEND_API_KEY}",
            "Content-Type": "application/json",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.status == 200, r.read().decode("utf-8", "replace")
    except Exception as e:
        return False, str(e)


def _esc(v):
    return str(v).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _badge_color(confidence: str) -> str:
    return {
        "High": "#16a34a", "Medium": "#d97706", "Low": "#dc2626",
    }.get(confidence, "#2563eb")


def render_toss_email(team_a: str, team_b: str, venue: str, toss_winner: str,
                      toss_decision: str, predicted_winner: str, no_bet: bool,
                      team_a_score: float, team_b_score: float, confidence: str,
                      key_factors: list) -> str:
    """Build the HTML body for a toss alert."""
    winner = "No Bet" if no_bet else (predicted_winner or "No Bet")
    confidence = confidence or "Low"

    factors = "".join(
        f'<li style="margin-bottom:8px;line-height:1.5;">{_esc(f)}</li>' for f in (key_factors or [])
    ) or "<li>Match analysis complete.</li>"

    return f"""
<div style="font-family:Arial,Helvetica,sans-serif;max-width:600px;margin:0 auto;padding:24px;">
  <div style="background:#1e293b;color:#fff;border-radius:12px 12px 0 0;padding:20px 24px;">
    <div style="font-size:12px;text-transform:uppercase;letter-spacing:2px;opacity:.8;">Match toss locked in</div>
    <h1 style="margin:6px 0 0;font-size:20px;">{_esc(team_a)} vs {_esc(team_b)}</h1>
    <div style="opacity:.75;font-size:13px;margin-top:4px;">{_esc(venue)}</div>
  </div>
  <div style="background:#fff;border:1px solid #e2e8f0;border-top:none;border-radius:0 0 12px 12px;padding:24px;">
    <div style="display:flex;gap:12px;margin-bottom:20px;flex-wrap:wrap;">
      <span style="background:#f1f5f9;border-radius:8px;padding:8px 14px;font-size:14px;">
        <b>Toss:</b> {_esc(toss_winner)} elected to {_esc(toss_decision).lower()}
      </span>
      <span style="background:{_badge_color(confidence)};color:#fff;border-radius:8px;padding:8px 14px;font-size:14px;">
        Call: <b>{_esc(winner)}</b> ({_esc(confidence)})
      </span>
    </div>
    <div style="display:flex;gap:24px;margin-bottom:20px;">
      <div><div style="font-size:12px;color:#64748b;">{_esc(team_a)}</div>
        <div style="font-size:24px;font-weight:700;">{team_a_score:.1f}%</div></div>
      <div><div style="font-size:12px;color:#64748b;">{_esc(team_b)}</div>
        <div style="font-size:24px;font-weight:700;">{team_b_score:.1f}%</div></div>
    </div>
    <h2 style="font-size:15px;margin:0 0 10px;">Key factors behind the call</h2>
    <ul style="padding-left:18px;margin:0;">{factors}</ul>
    <div style="margin-top:20px;padding-top:16px;border-top:1px solid #e2e8f0;font-size:12px;color:#64748b;">
      Generated by the MatchCall 10-layer prediction engine. Subscribe anytime from the MatchCall app.
    </div>
  </div>
</div>
"""